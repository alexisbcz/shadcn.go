//go:build ignore

// gen writes all_gen.go: a blank import of every examples/<component>
// package, so importing examples/all registers every ported example.
// Run with: go generate ./examples/all
package main

import (
	"fmt"
	"os"
	"slices"
)

func main() {
	entries, err := os.ReadDir("..")
	if err != nil {
		panic(err)
	}
	var pkgs []string
	for _, e := range entries {
		if !e.IsDir() || e.Name() == "all" || e.Name() == "registry" {
			continue
		}
		if files, _ := os.ReadDir("../" + e.Name()); len(files) > 0 {
			pkgs = append(pkgs, e.Name())
		}
	}
	slices.Sort(pkgs)
	out := "// Code generated by gen.go; DO NOT EDIT.\n\n// Package all links every ported example into the registry.\npackage all\n\nimport (\n"
	for _, p := range pkgs {
		out += fmt.Sprintf("\t_ %q\n", "shadcn.go/examples/"+p)
	}
	out += ")\n"
	if err := os.WriteFile("all_gen.go", []byte(out), 0o644); err != nil {
		panic(err)
	}
}
