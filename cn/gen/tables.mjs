#!/usr/bin/env node
// Generates cn/tables_gen.go from the compiled tables of the `cn` npm package
// (shadcn's clsx + tailwind-merge replacement), so the Go engine runs on
// exactly the tables upstream ships.
//
//   node cn/gen/tables.mjs [path/to/cn/dist/tables.js]
//
// Run from the repository root (or via `go generate ./cn`). The default input
// is ui/apps/v4/node_modules/cn/dist/tables.js, the version the upstream
// lockfile pins (0.2.2).
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { execFileSync } from "node:child_process"
import { fileURLToPath, pathToFileURL } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, "..", "..")
const src = resolve(process.argv[2] ?? join(root, "ui/apps/v4/node_modules/cn/dist/tables.js"))
const pkg = JSON.parse(readFileSync(join(dirname(src), "..", "package.json"), "utf8"))
const T = (await import(pathToFileURL(src).href)).default
const sha = createHash("sha256").update(readFileSync(src)).digest("hex")

const INT_ARRAYS = [
  "edgeStart", "labelStart", "edgeTarget", "nodeGroup", "nodeVlist",
  "vlistPat", "vlistOps", "vlistRef", "vlistGroup",
  "litAnchor", "litGroup", "litPool", "poolOffsets",
  "adjGid", "adjStart", "adjTgt", "patGid", "patTgt", "postfixLookupGroups",
]
const STRINGS = ["labelText", "poolText", "orderSensitiveModifiers"]

const known = new Set([...INT_ARRAYS, ...STRINGS, "GROUP_COUNT", "customValidatorNames", "prefix"])
for (const k of Object.keys(T)) if (!known.has(k)) throw new Error("unknown table field " + k)
if (T.customValidatorNames.length) throw new Error("custom validators are not supported")
if (T.prefix) throw new Error("prefixed tables are not supported")

// The engine compares table text with input code units; the Go port compares
// bytes. Both agree as long as the table text is ASCII.
for (const k of STRINGS) if (!/^[\x20-\x7e]*$/.test(T[k])) throw new Error(k + " is not printable ASCII")

const goName = (k) => k[0].toUpperCase() + k.slice(1)
let out = `// Code generated by cn/gen/tables.mjs from cn@${pkg.version} dist/tables.js; DO NOT EDIT.
// Source sha256: ${sha}
//
// cn is Copyright (c) 2026 shadcn, MIT License.

package cn

// Version is the version of the cn npm package the tables come from.
const Version = ${JSON.stringify(pkg.version)}

// tablesSHA256 is the sha256 of the dist/tables.js the tables come from.
const tablesSHA256 = ${JSON.stringify(sha)}

const groupCount = ${T.GROUP_COUNT}

`
for (const k of STRINGS) out += `const ${k} = ${JSON.stringify(T[k])}\n\n`
for (const k of INT_ARRAYS) {
  const a = Array.from(T[k])
  out += `var ${k} = [...]int32{`
  if (a.length) {
    out += "\n"
    for (let i = 0; i < a.length; i += 20) out += "\t" + a.slice(i, i + 20).join(", ") + ",\n"
  }
  out += "}\n\n"
}
const dst = join(root, "cn", "tables_gen.go")
writeFileSync(dst, out)
execFileSync("gofmt", ["-w", dst])
console.log("wrote", dst)
