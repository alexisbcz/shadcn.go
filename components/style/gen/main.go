// Command gen regenerates the data package style embeds, from the upstream
// clone in ./ui:
//
//   - css/style-<name>.css: the 8 style files, copied byte for byte from
//     ui/apps/v4/registry/styles.
//   - order.txt.gz: the Tailwind class order used to sort class strings the
//     way prettier-plugin-tailwindcss sorted upstream's generated sources.
//
// The order comes from Tailwind's own design system (the vendored
// tailwindcss 4.3.0 in shadcn.go/tailwind, run in goja with the same prelude
// that fixes goja's bugs), loaded from upstream's ui/apps/v4/app/globals.css,
// which is the stylesheet prettier-plugin-tailwindcss uses there
// (tailwindStylesheet). It lists every class found in the style files, in the
// differential test data and in the Go sources under -scan, ranked by
// getClassOrder, followed by the classes Tailwind does not know.
//
// Run from the repository root (go generate does this for you):
//
//	go run ./components/style/gen
package main

import (
	"bufio"
	"bytes"
	"compress/gzip"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"math/big"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/dop251/goja"
)

var styles = []string{"nova", "vega", "lyra", "maia", "mira", "luma", "sera", "rhea"}

func main() {
	root := flag.String("root", ".", "repository root")
	scan := flag.String("scan", "components,examples", "comma-separated directories whose Go string literals add classes to the order table")
	flag.Parse()
	if err := run(*root, strings.Split(*scan, ",")); err != nil {
		fmt.Fprintln(os.Stderr, "style/gen:", err)
		os.Exit(1)
	}
}

func run(root string, scan []string) error {
	root, err := filepath.Abs(root)
	if err != nil {
		return err
	}
	pkg := filepath.Join(root, "components/style")
	upstream := filepath.Join(root, "ui/apps/v4")

	// 1. Style files, verbatim.
	classes := map[string]bool{}
	for _, s := range styles {
		name := "style-" + s + ".css"
		b, err := os.ReadFile(filepath.Join(upstream, "registry/styles", name))
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(pkg, "css", name), b, 0o644); err != nil {
			return err
		}
		for _, m := range applyRe.FindAllStringSubmatch(string(b), -1) {
			addClasses(classes, m[1])
		}
	}

	// 2. Classes of the differential test data.
	refs, _ := filepath.Glob(filepath.Join(pkg, "testdata/ref/*.json.gz"))
	for _, f := range refs {
		if err := refClasses(f, classes); err != nil {
			return fmt.Errorf("%s: %w", f, err)
		}
	}

	// 3. String literals of Go sources (components authored in Go).
	for _, dir := range scan {
		if dir == "" {
			continue
		}
		if err := goClasses(filepath.Join(root, dir), classes); err != nil {
			return err
		}
	}

	list := make([]string, 0, len(classes))
	for c := range classes {
		list = append(list, c)
	}
	sort.Strings(list)

	known, unknown, err := classOrder(root, upstream, list)
	if err != nil {
		return err
	}
	var buf bytes.Buffer
	zw, _ := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	w := bufio.NewWriter(zw)
	fmt.Fprintf(w, "# Tailwind class order (tailwindcss %s, ui/apps/v4/app/globals.css). Generated by components/style/gen; do not edit.\n", "4.3.0")
	for _, c := range known {
		fmt.Fprintln(w, c)
	}
	fmt.Fprintln(w, "# unknown")
	for _, c := range unknown {
		fmt.Fprintln(w, c)
	}
	if err := w.Flush(); err != nil {
		return err
	}
	if err := zw.Close(); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(pkg, "order.txt.gz"), buf.Bytes(), 0o644); err != nil {
		return err
	}
	fmt.Printf("style/gen: %d style files, %d classes ordered, %d unknown to Tailwind\n", len(styles), len(known), len(unknown))
	return nil
}

var applyRe = regexp.MustCompile(`@apply\s+([^;]*);`)

// prettier-plugin-tailwindcss splits class strings on these characters.
var splitRe = regexp.MustCompile(`[\t\r\f\n ]+`)

func addClasses(set map[string]bool, s string) {
	for _, c := range splitRe.Split(s, -1) {
		if c != "" {
			set[c] = true
		}
	}
}

func refClasses(file string, set map[string]bool) error {
	f, err := os.Open(file)
	if err != nil {
		return err
	}
	defer f.Close()
	zr, err := gzip.NewReader(f)
	if err != nil {
		return err
	}
	var data any
	if err := json.NewDecoder(zr).Decode(&data); err != nil {
		return err
	}
	var walk func(v any)
	walk = func(v any) {
		switch v := v.(type) {
		case []any:
			for _, x := range v {
				walk(x)
			}
		case map[string]any:
			switch v["k"] {
			case "str":
				s, _ := v["v"].(string)
				addClasses(set, s)
			case "tpl":
				for _, q := range v["q"].([]any) {
					for _, s := range q.([]any) {
						addClasses(set, s.(string))
					}
				}
			}
			for _, x := range v {
				walk(x)
			}
		}
	}
	walk(data)
	return nil
}

func goClasses(dir string, set map[string]bool) error {
	return filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) {
				return nil
			}
			return err
		}
		if d.IsDir() {
			if d.Name() == "testdata" || d.Name() == "node_modules" {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(p, ".go") || strings.HasSuffix(p, "_test.go") {
			return nil
		}
		fset := token.NewFileSet()
		file, err := parser.ParseFile(fset, p, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil // not ours to fix; skip files that do not parse
		}
		ast.Inspect(file, func(n ast.Node) bool {
			if lit, ok := n.(*ast.BasicLit); ok && lit.Kind == token.STRING {
				if s, err := strconv.Unquote(lit.Value); err == nil && len(s) < 4096 {
					addClasses(set, s)
				}
			}
			return true
		})
		return nil
	})
}

// classOrder runs getClassOrder of Tailwind's design system over list and
// returns the known classes in order and the unknown ones.
func classOrder(root, upstream string, list []string) (known, unknown []string, err error) {
	lib, err := os.ReadFile(filepath.Join(root, "tailwind/dist/lib.js"))
	if err != nil {
		return nil, nil, err
	}
	prelude, err := tailwindPrelude(filepath.Join(root, "tailwind/engine.go"))
	if err != nil {
		return nil, nil, err
	}
	vm := goja.New()
	pre, err := vm.RunString(prelude)
	if err != nil {
		return nil, nil, err
	}
	preFn, _ := goja.AssertFunction(pre)
	warn := func(msg string) { fmt.Fprintln(os.Stderr, "tailwind:", msg) }
	if _, err := preFn(goja.Undefined(), vm.GlobalObject(), vm.ToValue(warn)); err != nil {
		return nil, nil, err
	}
	wrapper, err := vm.RunString("(function(module, exports){" + string(lib) + "\n})")
	if err != nil {
		return nil, nil, err
	}
	module, exports := vm.NewObject(), vm.NewObject()
	_ = module.Set("exports", exports)
	init, _ := goja.AssertFunction(wrapper)
	if _, err := init(goja.Undefined(), module, exports); err != nil {
		return nil, nil, err
	}

	glue, err := vm.RunString(`(function (tw, load, css, base, list, done, fail) {
  tw.__unstable__loadDesignSystem(css, {
    base: base,
    loadStylesheet: async (id, base) => load(id, base),
    loadModule: async (id) => { throw new Error("modules are not supported: " + id) },
  }).then(function (ds) {
    done(ds.getClassOrder(list).map(function (e) { return [e[0], e[1] === null ? null : e[1].toString()] }))
  }, function (e) { fail(String(e && e.stack || e)) })
})`)
	if err != nil {
		return nil, nil, err
	}
	fn, _ := goja.AssertFunction(glue)
	load := func(id, base string) (map[string]string, error) {
		p, err := resolveStylesheet(root, upstream, id, base)
		if err != nil {
			return nil, err
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return nil, err
		}
		return map[string]string{"path": p, "base": filepath.Dir(p), "content": string(b)}, nil
	}
	globals := filepath.Join(upstream, "app/globals.css")
	css, err := os.ReadFile(globals)
	if err != nil {
		return nil, nil, err
	}
	var (
		result  []any
		failure string
		done    bool
	)
	if _, err := fn(goja.Undefined(), module.Get("exports"), vm.ToValue(load), vm.ToValue(string(css)),
		vm.ToValue(filepath.Dir(globals)), vm.ToValue(list),
		vm.ToValue(func(v []any) { result, done = v, true }),
		vm.ToValue(func(msg string) { failure, done = msg, true })); err != nil {
		return nil, nil, err
	}
	if !done {
		return nil, nil, errors.New("loadDesignSystem did not complete")
	}
	if failure != "" {
		return nil, nil, errors.New(failure)
	}

	type ranked struct {
		name  string
		order *big.Int
	}
	var rs []ranked
	for _, e := range result {
		pair := e.([]any)
		name := pair[0].(string)
		if pair[1] == nil {
			unknown = append(unknown, name)
			continue
		}
		n, ok := new(big.Int).SetString(pair[1].(string), 10)
		if !ok {
			return nil, nil, fmt.Errorf("bad order %v for %q", pair[1], name)
		}
		rs = append(rs, ranked{name, n})
	}
	sort.SliceStable(rs, func(i, j int) bool { return rs[i].order.Cmp(rs[j].order) < 0 })
	for i, r := range rs {
		if i > 0 && rs[i-1].order.Cmp(r.order) == 0 {
			return nil, nil, fmt.Errorf("classes %q and %q share an order", rs[i-1].name, r.name)
		}
		known = append(known, r.name)
	}
	return known, unknown, nil
}

// resolveStylesheet resolves globals.css imports like the plugin does in
// ui/apps/v4: tailwindcss from the vendored package, other packages from
// upstream's node_modules, relative paths from disk.
func resolveStylesheet(root, upstream, id, base string) (string, error) {
	dist := filepath.Join(root, "tailwind/dist")
	switch id {
	case "tailwindcss":
		return filepath.Join(dist, "index.css"), nil
	case "tailwindcss/theme", "tailwindcss/theme.css":
		return filepath.Join(dist, "theme.css"), nil
	case "tailwindcss/preflight", "tailwindcss/preflight.css":
		return filepath.Join(dist, "preflight.css"), nil
	case "tailwindcss/utilities", "tailwindcss/utilities.css":
		return filepath.Join(dist, "utilities.css"), nil
	case "tw-animate-css":
		return filepath.Join(upstream, "node_modules/tw-animate-css/dist/tw-animate.css"), nil
	case "shadcn/tailwind.css":
		return filepath.Join(root, "ui/packages/shadcn/dist/tailwind.css"), nil
	}
	if strings.HasPrefix(id, "./") || strings.HasPrefix(id, "../") {
		p := filepath.Join(base, id)
		if base == dist || strings.HasPrefix(base, dist+string(filepath.Separator)) {
			return p, nil
		}
		if !strings.HasSuffix(p, ".css") {
			p += ".css"
		}
		return p, nil
	}
	return "", fmt.Errorf("cannot resolve stylesheet %q from %s", id, base)
}

// tailwindPrelude reads the goja prelude of package tailwind from its
// source, so both use the same fixes for goja's bugs.
func tailwindPrelude(file string) (string, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, file, nil, 0)
	if err != nil {
		return "", err
	}
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.CONST {
			continue
		}
		for _, s := range g.Specs {
			vs := s.(*ast.ValueSpec)
			for i, n := range vs.Names {
				if n.Name == "prelude" {
					lit, ok := vs.Values[i].(*ast.BasicLit)
					if !ok {
						return "", errors.New("tailwind prelude is not a literal")
					}
					return strconv.Unquote(lit.Value)
				}
			}
		}
	}
	return "", errors.New("tailwind prelude not found")
}
