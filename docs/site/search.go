// Search: components/command-menu.tsx, the header's search button and the
// command palette it opens (also with ⌘K, Ctrl+K or "/"). The palette is
// a cmdk Command in a Radix Dialog without overlay: the navigation items,
// the styles, the docs pages grouped by top-level folder (the components
// of the current base), the color palettes, and the full-text "Search
// Results" fetched from /api/search (searchindex.go).
//
// The markup is rendered here; command-menu.js (a runtime module) ports the
// behavior: the menu's own cmdk filter (value and keywords contain the
// search), keyboard and pointer selection, the footer that follows the
// highlighted item, the debounced search fetch, ⌘C and navigation.

//go:embed static/command-menu.js
var commandMenuJS string

func init() { runtime.Module("command-menu", commandMenuJS) }

// searchIndexPath is the route site.go registers for the search API.
const searchIndexPath = searchAPIPath

func (s *Site) serveSearchIndex(w http.ResponseWriter, r *http.Request) { s.serveSearch(w, r) }

//go:embed commandmenu.json
var commandMenuJSON []byte

// commandMenuData is generated by gen/command-menu.mjs from
// registry/styles.tsx (STYLES), shadcn/preset (encodePreset) and
// lib/colors.ts (getColors).
var commandMenuData struct {
	Styles []struct {
		Name, Title, Description, Icon, Href string
	}
	Colors []struct {
		Name   string
		Colors []struct{ ClassName, Hex, Oklch, Name string }
	}
}

func init() {
	if err := json.Unmarshal(commandMenuJSON, &commandMenuData); err != nil {
		panic(err)
	}
}

