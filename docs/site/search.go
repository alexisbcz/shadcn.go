// cmdk's visually hidden label style.
const cmSrOnly = "position:absolute;width:1px;height:1px;padding:0;margin:-1px;overflow:hidden;clip:rect(0, 0, 0, 0);white-space:nowrap;border-width:0"

// tabler's IconArrowRight, as @tabler/icons-react renders it.
const tablerArrowRight = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="tabler-icon tabler-icon-arrow-right "><path d="M5 12l14 0"></path><path d="M13 18l6 -6"></path><path d="M13 6l6 6"></path></svg>`

type cmItem struct {
	value    string
	keywords []string
	kind     string // page, component, style, color
	href     string
	copy     string // ⌘C payload: color class name, or the component name
	oklch    string
	children []any
}

func (it cmItem) node() h.Node {
	kw := ""
	if len(it.keywords) > 0 {
		b, _ := json.Marshal(it.keywords)
		kw = string(b)
	}
	return h.Div(h.Data("slot", "command-item"), h.Class(cmItemClass),
		h.Attr("cmdk-item", ""), h.Role("option"),
		h.Aria("disabled", "false"), h.Aria("selected", "false"),
		h.Data("disabled", "false"), h.Data("selected", "false"),
		h.Data("value", it.value),
		h.If(kw != "", h.Data("cmdk-keywords", kw)),
		h.Data("kind", it.kind),
		h.If(it.href != "", h.Data("href", it.href)),
		h.If(it.copy != "", h.Data("copy", it.copy)),
		h.If(it.oklch != "", h.Data("oklch", it.oklch)),
		h.Group(it.children...),
	)
}

func cmGroup(class, heading string, items []cmItem) h.Node {
	return h.Div(h.Data("slot", "command-group"), h.Class(class),
		h.Attr("cmdk-group", ""), h.Role("presentation"), h.Data("value", heading),
		h.Div(h.Attr("cmdk-group-heading", ""), h.Aria("hidden", "true"), heading),
		h.Div(h.Attr("cmdk-group-items", ""), h.Role("group"),
			h.Map(items, func(it cmItem) h.Node { return it.node() }),
		),
	)
}

func cmKbd(children ...any) h.Node {
	return h.El("kbd", h.Class(cmKbdClass), h.Group(children...))
}

// CommandMenu is the search button of the header and its dialog.
func (s *Site) CommandMenu(r *http.Request) h.Node {
	s.startSearchIndex()
	base := CurrentBase(r.URL.Path)

	var groups []any
	// Pages: siteConfig.navItems.
	var nav []cmItem
	for _, it := range NavItems {
		nav = append(nav, cmItem{
			value: "Navigation " + it.Label, keywords: []string{"nav", "navigation", strings.ToLower(it.Label)},
			kind: "page", href: it.Href,
			children: []any{h.UnsafeHTML(tablerArrowRight), it.Label},
		})
	}
	groups = append(groups, cmGroup(cmPageGroup, "Pages", nav))
	// Styles.
	var styles []cmItem
	for _, st := range commandMenuData.Styles {
		styles = append(styles, cmItem{
			value: "Style " + st.Title + " " + st.Description, keywords: []string{"style", "preset", st.Name, st.Title},
			kind: "style", href: st.Href,
			children: []any{h.UnsafeHTML(st.Icon), st.Title,
				h.Span(h.Class("ml-auto text-xs font-normal text-muted-foreground"), "Open style in shadcn/create")},
		})
	}
	groups = append(groups, cmGroup(cmPageGroup, "Styles", styles))
	// The docs pages, by top-level folder.
	for _, f := range s.Tree.Children {
		if f.Kind != pagetree.KindFolder {
			continue
		}
		pages := PagesFromFolder(f, base)
		if len(pages) == 0 {
			continue
		}
		var items []cmItem
		for _, p := range pages {
			isComponent := strings.Contains(p.URL, "/components/")
			it := cmItem{kind: "page", href: p.URL}
			if p.Name != "" {
				it.value = f.Name + " " + p.Name
			}
			icon := any(h.UnsafeHTML(tablerArrowRight))
			if isComponent {
				it.kind, it.keywords, it.copy = "component", []string{"component"}, path.Base(p.URL)
				icon = h.Div(h.Class("aspect-square size-4 rounded-full border border-dashed border-muted-foreground"))
			}
			it.children = []any{icon, p.Name}
			items = append(items, it)
		}
		groups = append(groups, cmGroup(cmPageGroup, f.Name, items))
	}
	// Colors.
	for _, pal := range commandMenuData.Colors {
		var items []cmItem
		for _, c := range pal.Colors {
			items = append(items, cmItem{
				value: c.ClassName, keywords: []string{"color", c.Name, c.ClassName},
				kind: "color", copy: c.ClassName, oklch: c.Oklch,
				children: []any{
					h.Div(h.Class("border-ghost aspect-square size-4 rounded-sm bg-(--color) after:rounded-sm"), h.Style("--color: "+c.Oklch)),
					c.ClassName,
					h.Span(h.Class("ml-auto font-mono text-xs font-normal text-muted-foreground tabular-nums"), c.Oklch),
				},
			})
		}
		heading := pal.Name
		if heading != "" {
			heading = strings.ToUpper(heading[:1]) + heading[1:]
		}
		groups = append(groups, cmGroup(cmColorGroup, heading, items))
	}

	command := h.Div(h.TabIndex(-1), h.Data("slot", "command"), h.Class(cmRootClass), h.Data("command-menu", ""),
		h.El("label", h.Attr("cmdk-label", ""), h.Style(cmSrOnly)),
		h.Div(h.Class("relative"),
			h.Div(h.Data("slot", "command-input-wrapper"), h.Class("flex h-9 items-center gap-2 border-b px-3"),
				lucide.Search(h.Class("size-4 shrink-0 opacity-50")),
				h.Input(h.Data("slot", "command-input"), h.Class(cmInputClass), h.Placeholder("Search documentation..."),
					h.Attr("cmdk-input", ""), h.Attr("autocomplete", "off"), h.Attr("autocorrect", "off"), h.Attr("spellcheck", "false"),
					h.Aria("autocomplete", "list"), h.Role("combobox"), h.Aria("expanded", "true"), h.Type("text"), h.Value("")),
			),
			h.Div(h.Data("command-menu-spinner", ""), h.Attr("hidden", ""),
				h.Class("pointer-events-none absolute top-1/2 right-3 z-10 flex -translate-y-1/2 items-center justify-center"),
				spinner.Spinner(h.Class("size-4 text-muted-foreground")),
			),
		),
		h.Div(h.Data("slot", "command-list"), h.Class(cmListClass), h.Attr("cmdk-list", ""), h.Role("listbox"), h.TabIndex(-1), h.Aria("label", "Suggestions"),
			h.Div(h.Attr("cmdk-list-sizer", ""),
				h.Div(h.Data("slot", "command-empty"), h.Class(cmEmptyClass), h.Attr("cmdk-empty", ""), h.Role("presentation"), h.Attr("hidden", ""), "No results found."),
				h.Group(groups...),
				// The "Search Results" group, filled by the script.
				h.Div(h.Data("slot", "command-group"), h.Class(cmResultsGrp), h.Attr("cmdk-group", ""), h.Role("presentation"),
					h.Data("value", "Search Results"), h.Data("command-menu-results", ""), h.Attr("hidden", ""),
					h.Div(h.Attr("cmdk-group-heading", ""), h.Aria("hidden", "true"), "Search Results"),
					h.Div(h.Attr("cmdk-group-items", ""), h.Role("group")),
				),
			),
		),
		// The prototype of a search result item.
		h.Template(h.Data("command-menu-result", ""),
			h.Div(h.Data("slot", "command-item"), h.Class(cmResultItem), h.Attr("cmdk-item", ""), h.Role("option"),
				h.Aria("disabled", "false"), h.Aria("selected", "false"), h.Data("disabled", "false"), h.Data("selected", "false"),
				h.Div(h.Class("line-clamp-1 text-sm")),
			),
		),
	)
	footer := h.Div(h.Class(cmFooter), h.Data("command-menu-footer", ""),
		h.Div(h.Class("flex items-center gap-2"),
			cmKbd(lucide.CornerDownLeft()), " ",
			h.Span(h.Data("command-menu-action", "")),
		),
		separator.Separator(separator.Vertical, h.Class("h-4!"), h.Data("command-menu-copy", ""), h.Attr("hidden", "")),
		h.Div(h.Class("flex items-center gap-1"), h.Data("command-menu-copy", ""), h.Attr("hidden", ""),
			cmKbd("⌘"), cmKbd("C"), h.Span(h.Data("command-menu-payload", "")),
		),
	)

	return dialog.Dialog(
		dialog.Trigger(lib.AsChild,
			button.Button(button.VariantOutline, h.Class(cmTriggerClass), h.Data("command-menu-trigger", ""),
				h.Span(h.Class("hidden xl:inline-flex"), "Search documentation..."),
				h.Span(h.Class("inline-flex xl:hidden"), "Search..."),
			),
		),
		primitive.Portal(
			primitive.Content(primitive.WithProps(h.Div(h.Data("slot", "dialog-content"), h.Class(cmContentClass))),
				dialog.Header(h.Class("sr-only"),
					dialog.Title("Search documentation..."),
					dialog.Description("Search for a command to run..."),
				),
				command,
				footer,
			),
		),
	)
}
