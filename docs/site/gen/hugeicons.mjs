// Generates docs/site/home_icons.go: the hugeicons (@hugeicons/core-free-icons)
// of the home page cards, as @hugeicons/react's HugeiconsIcon renders them
// with strokeWidth={2}.
//
// Usage: node docs/site/gen/hugeicons.mjs
import fs from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "../../..")
const pkg = path.join(root, "ui/node_modules/.pnpm/@hugeicons+core-free-icons@1.2.1/node_modules/@hugeicons/core-free-icons/dist/esm/index.js")
const icons = await import(pkg)
const cards = path.join(root, "ui/apps/v4/app/(app)/(root)/cards")
const names = new Set()
for (const f of fs.readdirSync(cards).filter((f) => f.endsWith(".tsx"))) {
  for (const [, n] of fs.readFileSync(path.join(cards, f), "utf8").matchAll(/\b([A-Z][A-Za-z0-9]*Icon)\b/g)) {
    if (icons[n]) names.add(n)
  }
}
const kebab = (k) => k.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase())
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;")
let out = `// Code generated by docs/site/gen/hugeicons.mjs; DO NOT EDIT.

package site

// The hugeicons of the home page cards: the inner markup of each icon, as
// HugeiconsIcon renders it with strokeWidth={2}.
var hugeicons = map[string]string{
`
for (const n of [...names].sort()) {
  let inner = ""
  for (const [tag, attrs] of icons[n]) {
    inner += `<${tag}`
    for (const [k, v] of Object.entries(attrs)) {
      if (k === "key") continue
      inner += ` ${kebab(k)}="${esc(k === "strokeWidth" ? 2 : v)}"`
    }
    inner += `></${tag}>`
  }
  out += `\t${JSON.stringify(n)}: ${JSON.stringify(inner)},\n`
}
out += "}\n"
fs.writeFileSync(path.join(root, "docs/site/home_icons.go"), out)
console.log(`${names.size} icons`)
