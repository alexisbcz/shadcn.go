// build.mjs regenerates ../dist/search.js and ../dist/LICENSES: the
// fumadocs-core 16.10.5 search code the docs site runs (remark-structure and
// the advanced Orama server behind app/api/search/route.ts), from the
// packages installed in ./ui, bundled unmodified by esbuild (an IIFE that
// sets globalThis.DocsSearch; see entry.mjs).
//
// Usage: node docs/search/gen/build.mjs
import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.resolve(here, "../../..")
const pnpm = path.join(repo, "ui/node_modules/.pnpm")
const esbuild = createRequire(path.join(pnpm, "esbuild@0.25.11/node_modules/esbuild/package.json"))("esbuild")
const dist = path.join(here, "../dist")
const dir = (prefix) => path.join(pnpm, fs.readdirSync(pnpm).find((d) => d.startsWith(prefix)), "node_modules")

const result = await esbuild.build({
  entryPoints: [path.join(here, "entry.mjs")],
  bundle: true,
  format: "iife",
  target: "es2020",
  platform: "neutral",
  mainFields: ["module", "main"],
  conditions: ["import", "default"],
  charset: "utf8",
  legalComments: "inline",
  nodePaths: [dir("fumadocs-core@16.10.5"), dir("remark-mdx@3.1.1"), dir("unified@11.0.5")],
  outfile: path.join(dist, "search.js"),
  metafile: true,
  logLevel: "error",
})

// goja has no Unicode property escapes (\p{...}). The few regex literals
// using them are rewritten with explicit BMP character classes computed
// here by V8. Each is only ever tested on one UTF-16 code unit (micromark's
// regexCheck tests String.fromCharCode(code)) or never run by the search
// code (GFM autolink literals, the MDX JSX parser), so the BMP is exact.
const bmpClass = (re) => {
  const hex = (c) => "\\u" + c.toString(16).padStart(4, "0")
  let out = "", start = -1
  for (let c = 0; c <= 0x10000; c++) {
    const ok = c < 0x10000 && !(c >= 0xd800 && c <= 0xdfff) && re.test(String.fromCharCode(c))
    if (ok && start < 0) start = c
    if (!ok && start >= 0) {
      out += c - 1 === start ? hex(start) : hex(start) + "-" + hex(c - 1)
      start = -1
    }
  }
  return out
}
const PS = bmpClass(/[\p{P}\p{S}]/u)
const IDS = bmpClass(/[$_\p{ID_Start}]/u)
const IDC = bmpClass(/[$_\u{200C}\u{200D}\p{ID_Continue}]/u)
const rewrites = [
  ["/\\p{P}|\\p{S}/u", `/[${PS}]/`],
  ["/[$_\\p{ID_Start}]/u", `/[${IDS}]/`],
  ["/[$_\\u{200C}\\u{200D}\\p{ID_Continue}]/u", `/[${IDC}]/`],
  ["/[-$_\\u{200C}\\u{200D}\\p{ID_Continue}]/u", `/[-${IDC}]/`],
  ["/(?<=^|\\s|\\p{P}|\\p{S})([-.\\w+]+)@([-\\w]+(?:\\.[-\\w]+)+)/gu", `/(?<=^|\\s|[${PS}])([-.\\w+]+)@([-\\w]+(?:\\.[-\\w]+)+)/g`],
]
let js = fs.readFileSync(path.join(dist, "search.js"), "utf8")
for (const [from, to] of rewrites) {
  if (!js.includes(from)) throw new Error("rewrite not found: " + from)
  js = js.split(from).join(to)
}
if (/\\p\{/.test(js)) throw new Error("unrewritten \\p{ in search.js")
fs.writeFileSync(path.join(dist, "search.js"), js)

const packages = new Map()
for (const input of Object.keys(result.metafile.inputs)) {
  const m = /\.pnpm\/([^/]+)\/node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input)
  if (m) packages.set(m[2], path.join(pnpm, m[1], "node_modules", m[2]))
}
let out = "Licenses of the packages bundled in search.js (generated by gen/build.mjs).\n"
for (const [name, d] of [...packages].sort()) {
  const pkg = JSON.parse(fs.readFileSync(path.join(d, "package.json"), "utf8"))
  const file = fs.readdirSync(d).find((f) => /^licen[sc]e/i.test(f))
  out += `\n${"=".repeat(78)}\n${name}@${pkg.version} (${pkg.license})\n${"=".repeat(78)}\n\n`
  out += file ? fs.readFileSync(path.join(d, file), "utf8").trim() + "\n" : `(no license file; package.json declares ${pkg.license})\n`
}
fs.writeFileSync(path.join(dist, "LICENSES"), out)
console.log(`${packages.size} packages bundled, ${fs.statSync(path.join(dist, "search.js")).size} bytes`)
