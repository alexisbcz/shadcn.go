// build.mjs regenerates ../dist/shiki.js and ../dist/LICENSES: shiki 3.23.0
// (the version rehype-pretty-code 0.14.1 resolves to in ui/apps/v4), its
// JavaScript regex engine, and the grammars and themes the docs use, from
// the packages installed in ./ui, bundled unmodified by esbuild (an IIFE
// that sets globalThis.Shiki; see entry.mjs).
//
// Usage: node docs/highlight/gen/build.mjs
import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.resolve(here, "../../..")
const pnpm = path.join(repo, "ui/node_modules/.pnpm")
const esbuild = createRequire(path.join(pnpm, "esbuild@0.25.11/node_modules/esbuild/package.json"))("esbuild")
const dist = path.join(here, "../dist")

const result = await esbuild.build({
  entryPoints: [path.join(here, "entry.mjs")],
  bundle: true,
  format: "iife",
  target: "esnext",
  charset: "utf8",
  legalComments: "inline",
  nodePaths: [path.join(pnpm, "shiki@3.23.0/node_modules")],
  outfile: path.join(dist, "shiki.js"),
  metafile: true,
  logLevel: "error",
})

// Collect the license of every bundled package.
const packages = new Map()
for (const input of Object.keys(result.metafile.inputs)) {
  const m = /\.pnpm\/([^/]+)\/node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input)
  if (m) packages.set(m[2], path.join(pnpm, m[1], "node_modules", m[2]))
}
let out = "Licenses of the packages bundled in shiki.js (generated by gen/build.mjs).\n"
for (const [name, dir] of [...packages].sort()) {
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"))
  const file = fs.readdirSync(dir).find((f) => /^licen[sc]e/i.test(f))
  out += `\n${"=".repeat(78)}\n${name}@${pkg.version} (${pkg.license})\n${"=".repeat(78)}\n\n`
  out += file ? fs.readFileSync(path.join(dir, file), "utf8").trim() + "\n" : `(no license file; package.json declares ${pkg.license})\n`
}
fs.writeFileSync(path.join(dist, "LICENSES"), out)
console.log(`${packages.size} packages bundled`)
