// langs.mjs writes ../langs_table.go: every language name (ids and aliases)
// shiki 3.23.0 bundles. rehype-pretty-code loads any of them on demand, so
// a code block in a bundled language the vendored bundle lacks must fail
// rather than fall back to plain text; names shiki does not know fall back
// to plain text upstream too.
//
// Usage: node docs/highlight/gen/langs.mjs
import fs from "node:fs"
import path from "node:path"
import { execFileSync } from "node:child_process"
import { fileURLToPath, pathToFileURL } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.resolve(here, "../../..")
const shiki = await import(pathToFileURL(path.join(repo, "ui/node_modules/.pnpm/shiki@3.23.0/node_modules/shiki/dist/index.mjs")).href)
const names = Object.keys(shiki.bundledLanguages).sort()
let out = "// Code generated by gen/langs.mjs from shiki 3.23.0; DO NOT EDIT.\n\npackage highlight\n\n"
out += "// bundledLanguages lists the language names (ids and aliases) shiki's\n// full bundle can load.\nvar bundledLanguages = map[string]bool{\n"
for (const n of names) out += `\t${JSON.stringify(n)}: true,\n`
out += "}\n"
fs.writeFileSync(path.join(here, "../langs_table.go"), out)
execFileSync("gofmt", ["-w", path.join(here, "../langs_table.go")])
console.log(`${names.length} language names`)
