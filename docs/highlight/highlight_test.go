package highlight

import (
	"compress/gzip"
	"encoding/json"
	"os"
	"testing"

	"shadcn.go/docs/hast"
)

type block struct {
	Lang, Meta, Code, HTML string
}

func loadBlocks(t *testing.T) []block {
	f, err := os.Open("testdata/blocks.json.gz")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	zr, err := gzip.NewReader(f)
	if err != nil {
		t.Fatal(err)
	}
	var blocks []block
	if err := json.NewDecoder(zr).Decode(&blocks); err != nil {
		t.Fatal(err)
	}
	return blocks
}

// TestBlocks highlights every distinct code block of the 316 docs pages and
// requires byte-identical HTML to upstream's pipeline (testdata generated by
// docs/oracle/build.mjs: rehype-pretty-code 0.14.1, shiki 3.23.0 with its
// default Oniguruma engine, the docs' transformer).
func TestBlocks(t *testing.T) {
	h, err := New()
	if err != nil {
		t.Fatal(err)
	}
	blocks := loadBlocks(t)
	failed := 0
	for i, b := range blocks {
		el, err := h.Block(b.Code, b.Lang, b.Meta)
		if err != nil {
			t.Errorf("block %d (%s %q): %v", i, b.Lang, b.Meta, err)
			failed++
			continue
		}
		if got := hast.ToHTML(el); got != b.HTML {
			failed++
			if failed <= 5 {
				t.Errorf("block %d (%s %q) differs:\n got: %s\nwant: %s", i, b.Lang, b.Meta, firstDiff(got, b.HTML), firstDiff(b.HTML, got))
			}
		}
	}
	t.Logf("%d blocks, %d identical, %d different", len(blocks), len(blocks)-failed, failed)
}

func firstDiff(a, b string) string {
	i := 0
	for i < len(a) && i < len(b) && a[i] == b[i] {
		i++
	}
	lo := max(i-150, 0)
	hi := min(i+150, len(a))
	return a[lo:hi]
}
