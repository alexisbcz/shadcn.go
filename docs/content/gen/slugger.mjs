// slugger.mjs generates ../slugger_table.go: the code points github-slugger
// 2.0.0 removes when it slugs a heading (its regex.js, which matches UTF-16
// code units, evaluated for every code point).
// Usage: node docs/content/gen/slugger.mjs
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const pkg = path.join(here, "../../../ui/node_modules/.pnpm/github-slugger@2.0.0/node_modules/github-slugger")
const { regex } = await import(pathToFileURL(path.join(pkg, "regex.js")).href)
const ranges = []
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue
  const s = String.fromCodePoint(cp)
  const r = s.replace(new RegExp(regex.source, "g"), "")
  if (r !== "" && r !== s) throw new Error("partial removal at " + cp.toString(16))
  if (r === "") {
    const last = ranges[ranges.length - 1]
    if (last && last[1] === cp - 1) last[1] = cp
    else ranges.push([cp, cp])
  }
}
let out = `// Code generated by gen/slugger.mjs from github-slugger 2.0.0 (ISC license,
// Copyright (c) 2015, Dan Flettre). DO NOT EDIT.

package content

// sluggerRemoved lists the code point ranges github-slugger removes.
var sluggerRemoved = [][2]rune{
`
for (const [a, b] of ranges) out += `\t{0x${a.toString(16)}, 0x${b.toString(16)}},\n`
out += "}\n"
fs.writeFileSync(path.join(here, "../slugger_table.go"), out)
console.log(ranges.length, "ranges")
