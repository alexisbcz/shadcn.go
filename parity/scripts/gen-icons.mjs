// Generates the Go icon packages from the exact npm versions the upstream
// examples use (lucide-react 0.474.0, @tabler/icons-react 3.34.1). Each
// icon's shapes are rendered with react-dom/server, so attribute names and
// values are byte-for-byte what React puts in the DOM.
//
//   node parity/scripts/gen-icons.mjs
import fs from "node:fs"
import path from "node:path"
import { createElement } from "react"
import { renderToStaticMarkup } from "react-dom/server"
import { execFileSync } from "node:child_process"

const root = path.resolve(import.meta.dirname, "../..")
const nm = path.join(root, "parity/node_modules")
const goString = (s) => JSON.stringify(s) // valid Go interpreted string for our ASCII markup

const shapes = (iconNode) =>
  iconNode.map(([tag, attrs]) => {
    const { key, ...rest } = attrs
    return renderToStaticMarkup(createElement(tag, rest))
  }).join("")

function header(pkg, doc) {
  return `// Code generated by parity/scripts/gen-icons.mjs; DO NOT EDIT.\n\n${doc}\npackage ${pkg}\n\nimport h "shadcn.go/libhtml"\n\n`
}

// --- lucide ---------------------------------------------------------------
{
  const dir = path.join(nm, "lucide-react/dist/esm/icons")
  const version = JSON.parse(fs.readFileSync(path.join(nm, "lucide-react/package.json"))).version
  const entries = []
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".js")).sort()) {
    const mod = await import(path.join(dir, f))
    if (!mod.default || !mod.__iconNode) continue
    const name = mod.default.displayName
    entries.push({ file: f.replace(/\.js$/, ""), name, node: mod.__iconNode })
  }
  // Aliases: "export { default as Loader2, ... } from './icons/loader-circle.js'"
  const index = fs.readFileSync(path.join(nm, "lucide-react/dist/esm/lucide-react.js"), "utf8")
  const canonical = new Map(entries.map((e) => [e.file, e.name]))
  const aliases = []
  for (const m of index.matchAll(/export \{([^}]*)\} from '\.\/icons\/([^']+)\.js'/g)) {
    const target = canonical.get(m[2])
    for (const part of m[1].split(",")) {
      const alias = part.trim().replace(/^default as /, "")
      if (!alias || alias === target || alias.endsWith("Icon") || alias.startsWith("Lucide")) continue
      aliases.push([alias, target])
    }
  }
  let out = header("lucide", `// Package lucide provides every Lucide icon (lucide-react ${version}, ISC license)\n// as a libhtml element rendering the same DOM as the React component.`)
  out += `// Version is the lucide-react version the icons were generated from.\nconst Version = ${goString(version)}\n\n`
  for (const e of entries) {
    const kebab = e.name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase()
    out += `// ${e.name} renders lucide's ${e.file} icon.\nfunc ${e.name}(children ...any) *h.Element { return icon(${goString(kebab)}, ${goString(shapes(e.node))}, children) }\n\n`
  }
  out += "// Aliases exported by lucide-react under other names.\nvar (\n"
  const seen = new Set(entries.map((e) => e.name))
  for (const [alias, target] of aliases.sort()) {
    if (seen.has(alias) || !/^[A-Z][A-Za-z0-9]*$/.test(alias)) continue
    seen.add(alias)
    out += `\t${alias} = ${target}\n`
  }
  out += ")\n"
  fs.writeFileSync(path.join(root, "components/icons/lucide/icons_gen.go"), out)
  console.log(`lucide: ${entries.length} icons, ${seen.size - entries.length} aliases`)
}

// --- tabler (only the icons the upstream registry imports) ------------------------------
{
  const used = new Set()
  const walk = (d) => {
    for (const f of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, f.name)
      if (f.isDirectory()) walk(p)
      else if (/\.(tsx?|mdx)$/.test(f.name)) {
        const src = fs.readFileSync(p, "utf8")
        for (const m of src.matchAll(/import\s*\{([^}]*)\}\s*from\s*"@tabler\/icons-react"/g))
          for (const n of m[1].split(",")) {
            const name = n.trim().split(/\s+as\s+/)[0]
            if (name && !name.startsWith("type ")) used.add(name)
          }
      }
    }
  }
  walk(path.join(root, "ui/apps/v4/registry"))
  const dir = path.join(nm, "@tabler/icons-react/dist/esm/icons")
  const version = JSON.parse(fs.readFileSync(path.join(nm, "@tabler/icons-react/package.json"))).version
  let out = header("tabler", `// Package tabler provides the Tabler icons (@tabler/icons-react ${version}, MIT\n// license) used by the shadcn/ui registry, rendering the same DOM as React.\n// Regenerate with parity/scripts/gen-icons.mjs to add more.`)
  out += `// Version is the @tabler/icons-react version the icons were generated from.\nconst Version = ${goString(version)}\n\n`
  for (const name of [...used].sort()) {
    const file = path.join(dir, name + ".mjs")
    if (!fs.existsSync(file)) { console.warn("tabler: missing", name); continue }
    const src = fs.readFileSync(file, "utf8")
    const m = src.match(/createReactComponent\("(\w+)", "([^"]+)", "[^"]+", __iconNode\)/)
    const mod = await import(file)
    out += `// ${name} renders tabler's ${m[2]} icon (${m[1]}).\nfunc ${name}(children ...any) *h.Element { return icon(${goString(m[1])}, ${goString(m[2])}, ${goString(shapes(mod.__iconNode))}, children) }\n\n`
  }
  fs.writeFileSync(path.join(root, "components/icons/tabler/icons_gen.go"), out)
  console.log(`tabler: ${used.size} icons`)
}

execFileSync("gofmt", ["-w", path.join(root, "components/icons")])
