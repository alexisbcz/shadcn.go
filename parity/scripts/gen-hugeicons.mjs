// Generates components/icons/hugeicons from @hugeicons/core-free-icons (the
// version the upstream app installs). Each icon is rendered with
// @hugeicons/react's HugeiconsIcon and strokeWidth={2}, as the shadcn/ui
// registry renders it, through react-dom/server: the shapes are byte-for-byte
// what React puts in the DOM.
//
//   node parity/scripts/gen-hugeicons.mjs
import fs from "node:fs"
import path from "node:path"
import { execFileSync } from "node:child_process"

const root = path.resolve(import.meta.dirname, "../..")
const pnpm = path.join(root, "ui/node_modules/.pnpm")
const corePkg = path.join(pnpm, "@hugeicons+core-free-icons@1.2.1/node_modules/@hugeicons/core-free-icons")
const reactDir = fs.readdirSync(pnpm).find((d) => d.startsWith("@hugeicons+react@"))
const icons = await import(path.join(corePkg, "dist/esm/index.js"))
const { HugeiconsIcon } = await import(path.join(pnpm, reactDir, "node_modules/@hugeicons/react/dist/esm/index.js"))
const reactDomDir = fs.readdirSync(pnpm).find((d) => d.startsWith("react-dom@19"))
const { createElement } = await import(path.join(pnpm, "react@19.2.3/node_modules/react/index.js"))
const { renderToStaticMarkup } = await import(path.join(pnpm, reactDomDir, "node_modules/react-dom/cjs/react-dom-server-legacy.node.production.js"))
const version = JSON.parse(fs.readFileSync(path.join(corePkg, "package.json"))).version

// Every icon is exported under several names (Add01Icon, AddIcon,
// Add01FreeIcons, ...); the first "...Icon" name is the canonical one.
const byData = new Map()
for (const [name, data] of Object.entries(icons)) {
  if (!Array.isArray(data) || !name.endsWith("Icon")) continue
  if (!byData.has(data)) byData.set(data, [])
  byData.get(data).push(name)
}
const goString = (s) => JSON.stringify(s)
const kebab = (n) => n.replace(/Icon$/, "").replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Za-z])([0-9])/g, "$1-$2").toLowerCase()
let out = `// Code generated by parity/scripts/gen-hugeicons.mjs; DO NOT EDIT.

// Package hugeicons provides the Hugeicons free icon set
// (@hugeicons/core-free-icons ${version}, MIT license) as libhtml elements
// rendering the same DOM as @hugeicons/react's HugeiconsIcon with
// strokeWidth={2}, as the shadcn/ui registry uses them.
package hugeicons

import h "shadcn.go/libhtml"

// Version is the @hugeicons/core-free-icons version the icons were generated from.
const Version = ${goString(version)}

`
const names = new Map()
const aliases = []
for (const [data, list] of byData) {
  const canonical = list[0]
  const svg = renderToStaticMarkup(createElement(HugeiconsIcon, { icon: data, strokeWidth: 2 }))
  const shapes = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "")
  names.set(canonical, kebab(canonical))
  out += `// ${canonical} renders the ${kebab(canonical)} icon.\nfunc ${canonical}(children ...any) *h.Element { return icon(${goString(shapes)}, children) }\n\n`
  for (const a of list.slice(1)) aliases.push([a, canonical])
}
out += "// Aliases: other names the package exports for the same icons.\nvar (\n"
for (const [a, c] of aliases.sort()) out += `\t${a} = ${c}\n`
out += ")\n\n// ByName maps each exported name (canonical or alias) to its icon.\nvar ByName = map[string]func(children ...any) *h.Element{\n"
for (const [a] of [...names, ...aliases].sort((x, y) => (x[0] < y[0] ? -1 : 1))) out += `\t${goString(a)}: ${a},\n`
out += "}\n"
// Check the wrapper against HugeiconsIcon's own <svg> once.
const sample = renderToStaticMarkup(createElement(HugeiconsIcon, { icon: icons.Add01Icon, strokeWidth: 2 }))
console.log("svg:", sample.match(/^<svg[^>]*>/)[0])
fs.writeFileSync(path.join(root, "components/icons/hugeicons/icons_gen.go"), out)
execFileSync("gofmt", ["-w", path.join(root, "components/icons/hugeicons/icons_gen.go")])
console.log(`hugeicons: ${byData.size} icons, ${aliases.length} aliases`)
